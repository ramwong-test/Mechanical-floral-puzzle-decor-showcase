// 由 ./models/ 資料夾重新產生 catalog.js(零件清單)。
// 用法:node catalog-gen.mjs
// 新增零件:把 .glb 放進對應資料夾後執行此檔,重新整理網頁即生效。
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const FLOWER_EN = { tulip: 'Tulip', mum: 'Mum', rose: 'Rose', lotus: 'Lotus' };
const M = join(import.meta.dirname, 'models');

const pieces = [];

// Pots
for (const f of readdirSync(join(M, 'Pot')).filter(f => f.endsWith('.glb'))) {
  const m = /^pot_\d+\.glb$/.exec(f);
  if (m) pieces.push({ id: f.replace(/\.glb$/, ''), kind: 'pot', path: `Pot/${f}` });
}

// Stems
for (const group of ['A', 'B']) {
  const dir = `Stem/${group}`;
  for (const f of readdirSync(join(M, dir)).filter(f => f.endsWith('.glb'))) {
    const m = /^stem_([13])([AB])_(\d+)(?:(_|)([LR]))?\.glb$/.exec(f);
    if (!m || m[2] !== group) continue;
    pieces.push({ id: f.replace(/\.glb$/, ''), kind: 'stem', group, len: +m[1], angle: +m[3], side: m[5] ?? null, path: `${dir}/${f}` });
  }
}

// Connectors (plain, in Connector/)
for (const f of readdirSync(join(M, 'Connector')).filter(f => f.endsWith('.glb'))) {
  const m = /^c_connector\.glb$/.exec(f);
  if (m) pieces.push({ id: f.replace(/\.glb$/, ''), kind: 'conn', leaf: null, path: `Connector/${f}` });
}
// Leaf connectors, in Leaf/Connector/
const leafConnDir = join(M, 'Leaf', 'Connector');
for (const f of readdirSync(leafConnDir).filter(f => f.endsWith('.glb'))) {
  const m = /^c_(tulip|mum|rose)_leaf_(a|b)_(l|r)\.glb$/.exec(f);
  if (!m) continue;
  const [, flower, variant, side] = m;
  pieces.push({
    id: f.replace(/\.glb$/, ''), kind: 'conn', leaf: { flower, variant, side },
    path: `Leaf/Connector/${f}`,
    display: `${FLOWER_EN[flower]} Leaf ${variant.toUpperCase()} ${side === 'l' ? 'Left' : 'Right'}`,
  });
}

// Flowers, in Flower/
for (const f of readdirSync(join(M, 'Flower')).filter(f => f.endsWith('.glb'))) {
  const id = f.replace(/\.glb$/, '');
  const m = /^e_(tulip|mum|rose|lotus)_anime\.glb$/.exec(f) || /^e_(tulip)_a_anime\.glb$/.exec(f);
  if (!m) continue;
  const flower = m[1] === 'lotus' ? 'lotus' : m[1];
  pieces.push({ id, kind: 'end', type: 'flower', flower, path: `Flower/${f}`, display: FLOWER_EN[flower] });
}
// Lotus-leaf ends, in Leaf/End/
for (const f of readdirSync(join(M, 'Leaf', 'End')).filter(f => f.endsWith('.glb'))) {
  const id = f.replace(/\.glb$/, '');
  const m = /^e_lotus_leaf_(a|b)\.glb$/.exec(f);
  if (!m) continue;
  pieces.push({ id, kind: 'end', type: 'lotus-leaf', leafVariant: m[1], path: `Leaf/End/${f}`, display: `Lotus Leaf ${m[1].toUpperCase()}` });
}

let out = `// AUTO-GENERATED by ./catalog-gen.mjs — piece metadata for the assembly app.\n`;
out += `export const CATALOG = ${JSON.stringify(pieces, null, 2)};\n`;
out += `export const byId = Object.fromEntries(CATALOG.map(p => [p.id, p]));\n`;
writeFileSync(join(import.meta.dirname, 'catalog.js'), out);
console.log('wrote catalog.js:', pieces.length, 'pieces,', pieces.filter(p => p.kind === 'stem').length, 'stems,', pieces.filter(p => p.kind === 'conn').length, 'connectors,', pieces.filter(p => p.kind === 'end').length, 'ends,', pieces.filter(p => p.kind === 'pot').length, 'pots');
